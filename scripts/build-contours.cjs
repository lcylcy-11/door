// Generates dist/horror/contours.js: loudness contours of the masking sounds, measured from the WAVs.
// The rules judge "covered" from these contours times the gain multiplier they also write to the
// audio graph, so what is judged and what is heard come from one source.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const audio = path.resolve(__dirname, '../dist/horror/assets/audio');
const STEP = .1, WINDOW = .5;
// Base gain each source plays at; contours are scaled so equal C means equal played loudness.
const SOURCES = { elevator: ['mask-elevator-loop', .5, true], traffic: ['mask-traffic-pass', .5, false], mimic: ['mimic-response', .65, false] };

function readWav(file) {
  const b = fs.readFileSync(file);
  if (b.toString('ascii', 0, 4) !== 'RIFF' || b.toString('ascii', 8, 12) !== 'WAVE') throw new Error(`${file}: not WAVE`);
  let offset = 12, format = null, data = null;
  while (offset + 8 <= b.length) {
    const id = b.toString('ascii', offset, offset + 4), size = b.readUInt32LE(offset + 4);
    if (id === 'fmt ') format = { channels: b.readUInt16LE(offset + 10), rate: b.readUInt32LE(offset + 12), bits: b.readUInt16LE(offset + 22) };
    if (id === 'data') data = b.subarray(offset + 8, offset + 8 + size);
    offset += 8 + size + (size & 1);
  }
  if (!format || !data || format.bits !== 16) throw new Error(`${file}: expected PCM16`);
  const frames = data.length / (2 * format.channels), power = new Float64Array(frames);
  for (let i = 0; i < frames; i++) {
    let sum = 0;
    for (let c = 0; c < format.channels; c++) { const v = data.readInt16LE((i * format.channels + c) * 2) / 32768; sum += v * v; }
    power[i] = sum / format.channels;
  }
  return { rate: format.rate, power, sha256: crypto.createHash('sha256').update(b).digest('hex') };
}
function rms(power, from, to, loop) {
  let sum = 0, n = 0;
  for (let i = from; i < to; i++) {
    let j = i;
    if (loop) j = ((i % power.length) + power.length) % power.length;
    else if (j < 0 || j >= power.length) { n++; continue; }
    sum += power[j]; n++;
  }
  return Math.sqrt(sum / Math.max(1, n));
}
const files = Object.fromEntries(Object.entries(SOURCES).map(([key, [id]]) => [key, readWav(path.join(audio, `${id}.wav`))]));
const reference = Math.sqrt(files.elevator.power.reduce((a, b) => a + b, 0) / files.elevator.power.length);
const out = { step: STEP, window: WINDOW, referenceDb: +(20 * Math.log10(reference)).toFixed(2), sources: {} };
for (const [key, [id, base, loop]] of Object.entries(SOURCES)) {
  const { rate, power, sha256 } = files[key], duration = power.length / rate, half = Math.round(WINDOW * rate / 2);
  const values = [];
  for (let t = 0; t <= duration - (loop ? STEP : 0) + 1e-9; t += STEP) {
    const centre = Math.round(t * rate);
    values.push(+((base / .5) * rms(power, centre - half, centre + half, loop) / reference).toFixed(3));
  }
  out.sources[key] = { file: id, base, loop, duration: +duration.toFixed(4), sha256, values };
}
const body = `// Generated by scripts/build-contours.cjs from the WAV files; do not edit by hand.\n` +
  `(function (root) {\n  'use strict';\n  const CONTOURS = ${JSON.stringify(out)};\n` +
  `  root.DoorContours = CONTOURS;\n  if (typeof module !== 'undefined') module.exports = CONTOURS;\n})(typeof window === 'undefined' ? globalThis : window);\n`;
const target = path.resolve(__dirname, '../dist/horror/contours.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== body) { console.error('contours.js is stale; run node scripts/build-contours.cjs'); process.exit(1); }
  console.log('contours.js matches the WAV files.');
} else { fs.writeFileSync(target, body); console.log(`Wrote ${target}`); }
for (const [key, s] of Object.entries(out.sources)) {
  const min = Math.min(...s.values), max = Math.max(...s.values), covered = s.values.filter(v => v >= .6).length * STEP;
  console.log(`${key}: C ${min}..${max}, >=0.60 for ${covered.toFixed(1)} s of ${s.duration} s`);
}
